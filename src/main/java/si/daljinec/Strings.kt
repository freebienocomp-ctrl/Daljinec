private val trCache = HashMap<String, Tr>()

/** Besedila v izbranem jeziku (neodvisno od jezika telefona). */
fun trFor(ctx: Context, lang: String): Tr = synchronized(trCache) {
    trCache.getOrPut(lang) { loadTr(ctx, lang) }
}

