/** Jezik telefona: sl, sr (tudi hr, bs, me) ali en. */
fun systemLang(): String = when (java.util.Locale.getDefault().language) {
    "sl" -> "sl"
    "sr", "hr", "bs", "sh", "me", "cnr" -> "sr"
    else -> "en"
}

